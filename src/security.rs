use core::fmt;
use std::future::Future;
use std::pin::Pin;
use std::sync::Arc;

use bytes::Bytes;
use http::{
    header,
    Extensions,
};
use serde::{
    Deserialize,
    Serialize,
};
use url::Url;

use crate::err::*;
use crate::internal::utils;

pub type SecurityHandler =
    Arc<dyn Fn(&str, &mut Extensions) -> Pin<Box<dyn Future<Output = Result<(), SecurityError>> + Send>> + Send + Sync>;

/// Represents a security scheme that can be used by the operations.
#[derive(Clone)]
pub struct Security {
    /// The type of the security scheme.
    pub r#type: SecurityType,
    /// A description for security scheme.
    pub description: Option<String>,
    /// A handler for implementing and performing authentication.
    pub handler: SecurityHandler,
}

impl Security {
    /// Performs authenticate as defined against a request.
    /// The defined `handler` may attach objects after authentication completion to `extentions`.
    pub(crate) async fn authenticate(
        &self,
        req: &http::Request<Bytes>,
        extentions: &mut Extensions,
    ) -> Result<(), SecurityError> {
        let token = match &self.r#type {
            SecurityType::Http { scheme, bearer_format } => utils::extract_auth_header(req, scheme)?,
            SecurityType::ApiKey { name, r#in } => {
                match r#in {
                    &In::Header => {
                        let value = req
                            .headers()
                            .get(name)
                            .ok_or_else(|| SecurityError::MissingApiKeyParameter)?;

                        value
                            .to_str()
                            .map_err(|_| SecurityError::InvalidUtf8HeaderValue)?
                            .to_owned()
                    }
                    &In::Query => {
                        let query = req.uri().query().unwrap_or_default();
                        let parsed = url::form_urlencoded::parse(query.as_bytes()).collect::<Vec<_>>();

                        let value = parsed
                            .iter()
                            .find(|(k, _)| k == name)
                            .map(|(_, v)| v.to_string())
                            .ok_or_else(|| SecurityError::MissingApiKeyParameter)?;

                        value
                    }
                    &In::Cookie => {
                        let cookie_header = req
                            .headers()
                            .get(header::COOKIE)
                            .ok_or_else(|| SecurityError::MissingApiKeyParameter)?;

                        let cookie_str = cookie_header
                            .to_str()
                            .map_err(|_| SecurityError::InvalidUtf8HeaderValue)?;

                        let value = utils::parse_cookie(cookie_str)
                            .iter()
                            .find(|(k, _)| k == name)
                            .map(|(_, v)| v.to_string())
                            .ok_or_else(|| SecurityError::MissingApiKeyParameter)?;

                        value
                    }
                }
            }
            SecurityType::OAuth2 { flows } => {
                return Err(SecurityError::Custom("OAuth2 is not yet supported".to_string()));
            }
            SecurityType::OpenIdConnect { open_id_connect_url } => {
                return Err(SecurityError::Custom("OpenID Connect is not yet supported".to_string()));
            }
            SecurityType::MutualTLS {} => {
                return Err(SecurityError::Custom("Mutual TLS is not yet supported".to_string()));
            }
        };

        (self.handler)(&token, extentions).await
    }
}

/// Represents the type of the security scheme.
#[derive(Debug, Clone)]
pub enum SecurityType {
    Http {
        /// The name of the HTTP Authentication scheme to be used
        /// in the Authorization header as defined in RFC7235.
        scheme: AuthenticationScheme,
        /// A hint to the client to identify how the bearer token is formatted.
        /// Bearer tokens are usually generated by an authorization server,
        /// so this information is primarily for documentation purposes.
        ///
        /// E.g., "JWT"
        bearer_format: Option<String>,
    },
    ApiKey {
        /// The name of the header, query or cookie parameter to be used.
        name: String,
        /// The location of the API key.
        r#in: In,
    },
    OAuth2 {
        /// An object containing configuration information for the flow types supported.
        flows: oauth2_flows::Security,
    },
    OpenIdConnect {
        /// Well-known URL to discover the [[OpenID-Connect-Discovery]] provider metadata.
        open_id_connect_url: Url,
    },
    MutualTLS {},
}

/// Represents authentication scheme registered in IANA Authentication Scheme registry.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum AuthenticationScheme {
    Basic,
    Bearer,
    Concealed,
    Digest,
    DPoP,
    GNAP,
    HOBA,
    Mutual,
    Negotiate,
    OAuth,
    PrivateToken,
    #[serde(rename = "SCRAM-SHA-1")]
    ScramSha1,
    #[serde(rename = "SCRAM-SHA-256")]
    ScramSha256,
    #[serde(rename = "vapid")]
    Vapid,
}

impl fmt::Display for AuthenticationScheme {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match serde_json::to_string(self) {
            Ok(json) => f.write_str(&json),
            Err(_) => f.write_str("<serialization error>"),
        }
    }
}

/// Represents the location of the API key.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum In {
    Query,
    Header,
    Cookie,
}

impl fmt::Display for In {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match serde_json::to_string(self) {
            Ok(json) => f.write_str(&json),
            Err(_) => f.write_str("<serialization error>"),
        }
    }
}

pub mod oauth2_flows {
    use url::Url;

    /// Represents configuration of the supported OAuth Flows.
    #[derive(Debug, Clone, Default)]
    pub struct Security {
        /// Configuration for the OAuth Implicit flow.
        pub implicit: Option<Implicit>,
        /// Configuration for the OAuth Resource Owner Password flow
        pub password: Option<Password>,
        /// Configuration for the OAuth Client Credentials flow.
        pub client_credentials: Option<ClientCredentials>,
        /// Configuration for the OAuth Authorization Code flow.
        pub authorization_code: Option<AuthorizationCode>,
    }

    #[derive(Debug, Clone)]
    pub struct Implicit {
        pub authorization_url: Url,
        pub refrest_url: Option<Url>,
        pub scopes: Vec<(String, String)>,
    }

    #[derive(Debug, Clone)]
    pub struct Password {
        pub token_url: Url,
        pub refrest_url: Option<Url>,
        pub scopes: Vec<(String, String)>,
    }

    #[derive(Debug, Clone)]
    pub struct ClientCredentials {
        pub token_url: Url,
        pub refrest_url: Option<Url>,
        pub scopes: Vec<(String, String)>,
    }

    #[derive(Debug, Clone)]
    pub struct AuthorizationCode {
        pub authorization_url: Url,
        pub token_url: Url,
        pub refrest_url: Option<Url>,
        pub scopes: Vec<(String, String)>,
    }
}
